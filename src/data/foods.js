export const BUILTIN_FOODS = R.map(([name, kcal, p, c, f, s, aliases]) => ({
  key: `b:${name}`,
  name,
  per100: { kcal, p, c, f },
  servings: [{ label: s[0], grams: s[1] }],
  source: 'builtin',
  search: `${name} ${aliases}`.toLowerCase(),
}));
export const searchBuiltin = (q) => {
  const words = q.toLowerCase().trim().split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  return BUILTIN_FOODS
    .filter((f) => words.every((w) => f.search.includes(w)))
    .sort((a, b) => Number(b.name.toLowerCase().startsWith(words[0])) - Number(a.name.toLowerCase().startsWith(words[0])));
};
